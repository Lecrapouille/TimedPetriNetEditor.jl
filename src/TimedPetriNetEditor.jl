# Path of the native library, generated by deps/build.jl. When the package has
# not been built yet (or the C++ build failed), `libtpne` is empty and every
# native call raises a clear error instead of crashing precompilation.
const _DEPS = joinpath(@__DIR__, "..", "deps", "deps.jl")
if isfile(_DEPS)
    include(_DEPS)
else
    const libtpne = ""
end

function __init__()
    if isempty(libtpne) || !isfile(libtpne)
        @warn """TimedPetriNetEditor: native library not found.
                 Run `import Pkg; Pkg.build("TimedPetriNetEditor")` (a C++ \
                 toolchain, git, zeromq and OpenGL/glfw/glew are required). \
                 Native calls will fail until the library is built.""" libtpne
    end
end

# Raise a clear error if the native lib is missing at call time.
@inline function _checklib()
    (isempty(libtpne) || !isfile(libtpne)) &&
        error("TimedPetriNetEditor native library is not available. Run " *
              "`import Pkg; Pkg.build(\"TimedPetriNetEditor\")`.")
    return nothing
end

"""
    PetriNet

Immutable structure holding the handle of a Petri net. Since the Petri net
comes from a C++ class, the handle is simply the index of the container in
which it is held. This handle is never invalidated even if the container
changes of size.
"""
struct PetriNet
    handle::Int64
end

"""
    Place

Immutable structure holding information of a Petri place (X-Y coordinate in the
window and number of tokens). The unique identifier is the index of the Place.
"""
struct Place
    x::Float64
    y::Float64
    tokens::Int64
end

"""
    Transition

Immutable structure holding information of a Petri transition (X-Y coordinate in
the window). The unique identifier is the index of the Transition.
"""
struct Transition
    x::Float64
    y::Float64
end

"""
    Arc

Immutable structure holding information of a Petri Arc (origin and destination
nodes and duration). Node identifiers are strings "P0", "P1" ... for places and
"T0", "T1" ... for transitions.
"""
struct Arc
    from::String
    to::String
    duration::Float64
end

throw_error() = error("Invalid Petri net handle. Please use handles returned by petri_net()")

# Helper struct mapping the C sparse matrix (data are Max-Plus values). The data
# pointer must use the *concrete* `MP{Float64}` (== `Tropical{Max,Float64}`):
# `MP` alone is a `UnionAll` and `Ptr{MP}` would be rejected by `unsafe_load`.
mutable struct CSparse
    i::Ptr{Csize_t}
    j::Ptr{Csize_t}
    d::Ptr{MP{Float64}}
    size::Csize_t
    N::Csize_t
    M::Csize_t
    CSparse() = new(Ptr{Csize_t}(), Ptr{Csize_t}(), Ptr{MP{Float64}}(), 0, 0, 0)
end

# Helper struct mapping the C CCriticalCycle_t (see src/julia/Julia.hpp).
mutable struct CCriticalCycle
    durations::Ptr{Cdouble}
    eigenvector::Ptr{Cdouble}
    size::Csize_t
    cycles::Csize_t
    success::Bool
    CCriticalCycle() = new(Ptr{Cdouble}(), Ptr{Cdouble}(), 0, 0, false)
end

# Copy a C array into a Julia vector.
function from_c_arr(p::Ptr{T}, s::Csize_t) where T
    V = Vector{T}(undef, s)
    for i in 1:s
        V[i] = unsafe_load(p, i)
    end
    return V
end

"""
    petri_net()

Create an empty Petri net and return its handle. You can create several nets.
"""
function petri_net()
    _checklib()
    PetriNet(ccall((:petri_create, libtpne), Clonglong, ()))
end

"""
    petri_net(file::String)

Load a Petri net from a JSON file and return its handle.
"""
function petri_net(file::String)
    pn = petri_net()
    load_petri!(pn, file)
    return pn
end

"""
    petri_net(pn::PetriNet)

Duplicate the Petri net. Return the new handle.
"""
function petri_net(pn::PetriNet)
    _checklib()
    pn1 = ccall((:petri_copy, libtpne), Clonglong, (Clonglong,), pn.handle)
    (pn1 < 0) && throw_error()
    PetriNet(pn1)
end

"""
    is_empty(pn::PetriNet)

Check if the Petri net has no places and no transitions.
"""
function is_empty(pn::PetriNet)
    _checklib()
    empty = Ref{Bool}(false)
    ccall((:petri_is_empty, libtpne), Bool, (Clonglong, Ref{Bool}),
          pn.handle, empty) || throw_error()
    return empty[]
end

"""
    clear!(pn::PetriNet)

Clear the Petri net: remove all nodes and arcs.
"""
function clear!(pn::PetriNet)
    _checklib()
    ccall((:petri_reset, libtpne), Bool, (Clonglong,), pn.handle) || throw_error()
end

"""
    petri_editor!(pn::PetriNet; critical_cycle=false)

Launch the GUI editor to edit the net graphically. Once ESCAPE is pressed the
editor quits and modifications are applied on the net. Pass `critical_cycle=true`
to highlight the critical cycle and open its report dialog on startup.
"""
function petri_editor!(pn::PetriNet; critical_cycle::Bool = false)
    _checklib()
    ccall((:petri_editor, libtpne), Bool, (Clonglong, Ptr{Cchar}, Bool),
          pn.handle, C_NULL, critical_cycle) || throw_error()
end

"""
    petri_editor(pn::PetriNet; critical_cycle=false)

Duplicate the Petri net and launch the GUI editor on the copy. The original net
is left unmodified. Return the new handle.
"""
function petri_editor(pn::PetriNet; critical_cycle::Bool = false)
    pn1 = petri_net(pn)
    ccall((:petri_editor, libtpne), Bool, (Clonglong, Ptr{Cchar}, Bool),
          pn1.handle, C_NULL, critical_cycle) || throw_error()
    return pn1
end

"""
    add_place!(pn::PetriNet, x::Float64, y::Float64, tokens::Int)
    add_place!(pn::PetriNet, p::Place)

Add a new Place at coordinate X-Y with the given number of tokens. Return the
identifier of the newly created place.
"""
function add_place!(pn::PetriNet, x::Float64, y::Float64, tokens::Int)
    _checklib()
    (tokens < 0) && error("Number of tokens shall be >= 0")
    id = ccall((:petri_add_place, libtpne), Clonglong,
               (Clonglong, Cdouble, Cdouble, Clonglong), pn.handle, x, y, tokens)
    (id < 0) && throw_error()
    return id
end

function add_place!(pn::PetriNet, p::Place)
    add_place!(pn, p.x, p.y, p.tokens)
end

"""
    remove_place!(pn::PetriNet, id::Int)

