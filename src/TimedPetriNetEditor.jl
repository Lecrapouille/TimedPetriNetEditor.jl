# =============================================================================
# Flowshop / critical cycle: the ScicosLab functions missing from MaxPlus.jl.
# `G` is the `.flowshop` file produced by `MaxPlus.save_flowshop` (pure Julia),
# so there is no dependency cycle between the two packages.
# =============================================================================

"""
    import_flowshop!(pn::PetriNet, filename::AbstractString)

Build a flowshop timed event graph into `pn` from a `.flowshop` description
file (the format written by `MaxPlus.save_flowshop`). The net is reset first.
Return `pn`.
"""
function import_flowshop!(pn::PetriNet, filename::AbstractString)
    _checklib()
    isfile(filename) || error("Flowshop file not found: '$filename'")
    ccall((:petri_import_flowshop, libtpne), Bool, (Clonglong, Cstring),
          pn.handle, filename) || error("Failed importing flowshop file '$filename'")
    return pn
end

"""
    find_critical_cycle(pn::PetriNet)

Compute the critical cycle (semi-Howard) of the event graph held by `pn`.
Return a named tuple `(; success, cycles, durations, eigenvector)` where
`durations` is the cycle-time vector (the (max,+) eigenvalue per transition).
"""
function find_critical_cycle(pn::PetriNet)
    _checklib()
    result = Ref(CCriticalCycle())
    ok = ccall((:petri_find_critical_cycle, libtpne), Bool,
               (Clonglong, Ptr{CCriticalCycle}), pn.handle, result)
    r = result[]
    durations = from_c_arr(r.durations, r.size)
    eigenvector = from_c_arr(r.eigenvector, r.size)
    return (success = ok, cycles = Int(r.cycles),
            durations = durations, eigenvector = eigenvector)
end

"""
    show_cr_graph(G::AbstractString; editor=false)

ScicosLab-style `show_cr_graph`: load the `.flowshop` graph `G` (a file path,
typically produced by `MaxPlus.save_flowshop`), print its critical-cycle report
and return the result of [`find_critical_cycle`](@ref). Pass `editor=true` to
also open the GUI editor on the built network.
"""
function show_cr_graph(G::AbstractString; editor::Bool = false)
    pn = petri_net()
    import_flowshop!(pn, G)
    ccall((:petri_show_critical_cycle, libtpne), Bool, (Clonglong,), pn.handle)
    res = find_critical_cycle(pn)
    editor && petri_editor!(pn; critical_cycle = true)
    return res
end

"""
    show_cr_graph(E, m, p; machine_names, piece_names, editor=false)

Convenience overload: write `E`, `m`, `p` to a temporary `.flowshop` file with
`MaxPlus.save_flowshop`, then call [`show_cr_graph(::AbstractString)`](@ref).
"""
function show_cr_graph(E::AbstractMatrix, m::AbstractVector, p::AbstractVector;
                       machine_names = ["M$(j)" for j in 1:size(E, 1)],
                       piece_names = ["P$(i)" for i in 1:size(E, 2)],
                       editor::Bool = false)
    path = MaxPlus.save_flowshop(E, m, p, tempname() * ".flowshop";
                                 machine_names = machine_names, piece_names = piece_names)
    return show_cr_graph(path; editor = editor)
end

