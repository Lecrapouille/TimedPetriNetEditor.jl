"""
    to_graph(pn::PetriNet)

If and only if the Petri net is an event graph, generate two adjacency (max,+)
matrices: the first holds the token counts (`N`) and the second the durations
(`T`). Values are of type `MP` (see `MaxPlus.jl`).
"""
function to_graph(pn::PetriNet)
    _checklib()
    N = Ref(CSparse())
    T = Ref(CSparse())
    ccall((:petri_to_adjacency_matrices, libtpne), Bool,
          (Clonglong, Ptr{CSparse}, Ptr{CSparse}), pn.handle, N, T) ||
        error("Invalid Petri net handle")
    ns = N[].size
    ts = T[].size
    return (
        sparse(from_c_arr(N[].i, ns), from_c_arr(N[].j, ns), from_c_arr(N[].d, ns), N[].N, N[].M),
        sparse(from_c_arr(T[].i, ts), from_c_arr(T[].j, ts), from_c_arr(T[].d, ts), T[].N, T[].M),
    )
end

"""
    to_syslin(pn::PetriNet)

If and only if the Petri net is an event graph, generate the implicit dynamic
linear (max,+) system: `X(n) = D.X(n) ⨁ A.X(n-1) ⨁ B.U(n)`, `Y(n) = C.X(n)`.
"""
function to_syslin(pn::PetriNet)
    _checklib()
    A = Ref(CSparse()); B = Ref(CSparse()); C = Ref(CSparse()); D = Ref(CSparse())
    ccall((:petri_to_sys_lin, libtpne), Bool,
          (Clonglong, Ptr{CSparse}, Ptr{CSparse}, Ptr{CSparse}, Ptr{CSparse}),
          pn.handle, D, A, B, C) || error("Invalid Petri net handle")
    as = A[].size; bs = B[].size; cs = C[].size; ds = D[].size
    SD = sparse(from_c_arr(D[].i, ds), from_c_arr(D[].j, ds), from_c_arr(D[].d, ds), D[].N, D[].M)
    SA = sparse(from_c_arr(A[].i, as), from_c_arr(A[].j, as), from_c_arr(A[].d, as), A[].N, A[].M)
    SB = sparse(from_c_arr(B[].i, bs), from_c_arr(B[].j, bs), from_c_arr(B[].d, bs), B[].N, B[].M)
    SC = sparse(from_c_arr(C[].i, cs), from_c_arr(C[].j, cs), from_c_arr(C[].d, cs), C[].N, C[].M)
    return MPSysLin(SA, SB, SC, SD)
end

